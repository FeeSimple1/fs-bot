"""Forced Marches regressions: Card Reference 32, including its Scouted tip.

The mixed-seat seed 213 soak moved two Arverni Allies out of Sequani,
leaving their Tribes behind. Only the executing faction's mobile forces
may relocate; the Hidden instruction applies only to pieces actually moved.
"""

from copy import deepcopy

import pytest

from fs_bot import rules_consts as rc
from fs_bot.board.pieces import (
    PieceError,
    count_pieces,
    count_pieces_by_state,
    get_leader_in_region,
    place_piece,
)
from fs_bot.cards.card_effects import execute_card_32, execute_event
from fs_bot.state.setup import setup_scenario
from fs_bot.state.state_schema import (
    build_initial_state,
    check_structural_integrity,
    validate_state,
)


def _move(piece_type, *, count=1, **kwargs):
    return {
        "from_region": rc.SEQUANI,
        "to_region": rc.AEDUI_REGION,
        "piece_type": piece_type,
        "count": count,
        **kwargs,
    }


def _assert_sound(state):
    assert validate_state(state) == []
    assert check_structural_integrity(state) == []


@pytest.mark.parametrize("shaded", [False, True])
def test_seed213_static_choices_leave_allied_tribes_in_place(shaded):
    state = setup_scenario(rc.SCENARIO_GREAT_REVOLT, seed=213)
    state["executing_faction"] = rc.ARVERNI
    # Exact moves generated by the failing mixed-seat seed, followed by a
    # valid relocation to prove partial execution still carries it out.
    state["event_params"] = {"moves": [
        _move(rc.ALLY, count=2, piece_state=None),
        _move(rc.FORT, from_region=rc.MANDUBII, to_region=rc.BRITANNIA,
              count=2, piece_state=rc.REVEALED),
        _move(rc.WARBAND),
    ]}
    tribes_before = deepcopy(state["tribes"])
    allies_before = count_pieces(state, rc.AEDUI_REGION, rc.ARVERNI, rc.ALLY)
    warbands_before = count_pieces(state, rc.AEDUI_REGION, rc.ARVERNI,
                                   rc.WARBAND)
    _assert_sound(state)

    execute_event(state, 32, shaded=shaded)

    assert state["tribes"] == tribes_before
    assert count_pieces(state, rc.SEQUANI, rc.ARVERNI, rc.ALLY) == 2
    assert count_pieces(state, rc.AEDUI_REGION, rc.ARVERNI,
                        rc.ALLY) == allies_before
    assert count_pieces(state, rc.AEDUI_REGION, rc.ARVERNI,
                        rc.WARBAND) == warbands_before + 1
    _assert_sound(state)


@pytest.mark.parametrize("piece_type,faction,scenario", [
    (rc.ALLY, rc.ARVERNI, rc.SCENARIO_PAX_GALLICA),
    (rc.CITADEL, rc.ARVERNI, rc.SCENARIO_PAX_GALLICA),
    (rc.FORT, rc.ROMANS, rc.SCENARIO_PAX_GALLICA),
    (rc.SETTLEMENT, rc.GERMANS, rc.SCENARIO_ARIOVISTUS),
])
def test_static_piece_types_cannot_be_relocated(piece_type, faction, scenario):
    state = build_initial_state(scenario, seed=32)
    place_piece(state, rc.SEQUANI, faction, piece_type)
    if piece_type in (rc.ALLY, rc.CITADEL):
        state["tribes"][rc.TRIBE_SEQUANI]["allied_faction"] = faction
    state["executing_faction"] = faction
    state["event_params"] = {"moves": [_move(piece_type)]}
    before = {key: deepcopy(state[key])
              for key in ("spaces", "tribes", "available")}
    _assert_sound(state)

    execute_card_32(state)

    assert {key: state[key] for key in before} == before
    _assert_sound(state)


@pytest.mark.parametrize("piece_type,faction,selected_state", [
    (rc.WARBAND, rc.ARVERNI, "omitted"),
    (rc.WARBAND, rc.ARVERNI, None),
    (rc.WARBAND, rc.ARVERNI, rc.HIDDEN),
    (rc.WARBAND, rc.ARVERNI, rc.REVEALED),
    (rc.WARBAND, rc.ARVERNI, rc.SCOUTED),
    (rc.AUXILIA, rc.ROMANS, "omitted"),
    (rc.AUXILIA, rc.ROMANS, None),
    (rc.AUXILIA, rc.ROMANS, rc.HIDDEN),
    (rc.AUXILIA, rc.ROMANS, rc.REVEALED),
])
def test_only_moved_pieces_change_visibility(piece_type, faction, selected_state):
    state = build_initial_state(rc.SCENARIO_PAX_GALLICA, seed=32)
    actual_state = (rc.HIDDEN if selected_state in (None, "omitted")
                    else selected_state)
    place_piece(state, rc.SEQUANI, faction, piece_type, 3,
                piece_state=actual_state)
    place_piece(state, rc.AEDUI_REGION, faction, piece_type, 1,
                piece_state=rc.HIDDEN)
    place_piece(state, rc.AEDUI_REGION, faction, piece_type, 4,
                piece_state=rc.REVEALED)
    if piece_type == rc.WARBAND:
        place_piece(state, rc.AEDUI_REGION, faction, piece_type, 1,
                    piece_state=rc.SCOUTED)
    move = _move(piece_type, count=2)
    if selected_state != "omitted":
        move["piece_state"] = selected_state
    state["executing_faction"] = faction
    state["event_params"] = {"moves": [move]}

    execute_event(state, 32)

    assert count_pieces_by_state(state, rc.SEQUANI, faction,
                                 piece_type, actual_state) == 1
    # Card 32's tip: moved Scouted Warbands become Revealed, not Hidden.
    expected_hidden = 1 if actual_state == rc.SCOUTED else 3
    expected_revealed = 6 if actual_state == rc.SCOUTED else 4
    assert count_pieces_by_state(state, rc.AEDUI_REGION, faction,
                                 piece_type, rc.HIDDEN) == expected_hidden
    assert count_pieces_by_state(state, rc.AEDUI_REGION, faction,
                                 piece_type, rc.REVEALED) == expected_revealed
    expected_scouted = 1 if piece_type == rc.WARBAND else 0
    assert count_pieces_by_state(state, rc.AEDUI_REGION, faction,
                                 piece_type, rc.SCOUTED) == expected_scouted
    _assert_sound(state)


def test_legions_and_leader_can_relocate_to_nonadjacent_region():
    state = build_initial_state(rc.SCENARIO_PAX_GALLICA, seed=32)
    place_piece(state, rc.SEQUANI, rc.ROMANS, rc.LEGION, 2,
                from_legions_track=True)
    place_piece(state, rc.SEQUANI, rc.ROMANS, rc.LEADER,
                leader_name=rc.CAESAR)
    state["executing_faction"] = rc.ROMANS
    state["event_params"] = {"moves": [
        _move(rc.LEGION, count=2, to_region=rc.MORINI),
        _move(rc.LEADER, to_region=rc.MORINI),
    ]}

    execute_event(state, 32)

    assert count_pieces(state, rc.SEQUANI, rc.ROMANS, rc.LEGION) == 0
    assert count_pieces(state, rc.MORINI, rc.ROMANS, rc.LEGION) == 2
    assert get_leader_in_region(state, rc.SEQUANI, rc.ROMANS) is None
    assert get_leader_in_region(state, rc.MORINI, rc.ROMANS) == rc.CAESAR
    _assert_sound(state)


def test_only_executing_factions_pieces_move():
    state = build_initial_state(rc.SCENARIO_PAX_GALLICA, seed=32)
    for faction in (rc.ARVERNI, rc.BELGAE):
        place_piece(state, rc.SEQUANI, faction, rc.WARBAND, 2)
    state["executing_faction"] = rc.ARVERNI
    state["event_params"] = {"moves": [
        _move(rc.WARBAND, count=2, faction=rc.BELGAE),
    ]}

    execute_event(state, 32)

    assert count_pieces(state, rc.SEQUANI, rc.BELGAE, rc.WARBAND) == 2
    assert count_pieces(state, rc.AEDUI_REGION, rc.BELGAE, rc.WARBAND) == 0
    assert count_pieces(state, rc.SEQUANI, rc.ARVERNI, rc.WARBAND) == 0
    assert count_pieces(state, rc.AEDUI_REGION, rc.ARVERNI, rc.WARBAND) == 2
    _assert_sound(state)


