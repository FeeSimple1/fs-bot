@pytest.mark.parametrize("reverse_order", [False, True])
def test_original_groups_can_exchange_regions_without_visibility_confusion(reverse_order):
    state = build_initial_state(rc.SCENARIO_PAX_GALLICA, seed=32)
    place_piece(state, rc.SEQUANI, rc.ARVERNI, rc.WARBAND, 2,
                piece_state=rc.SCOUTED)
    place_piece(state, rc.AEDUI_REGION, rc.ARVERNI, rc.WARBAND, 3,
                piece_state=rc.REVEALED)
    moves = [
        _move(rc.WARBAND, count=2, piece_state=rc.SCOUTED),
        _move(rc.WARBAND, from_region=rc.AEDUI_REGION,
              to_region=rc.SEQUANI, count=2, piece_state=rc.REVEALED),
    ]
    state["executing_faction"] = rc.ARVERNI
    state["event_params"] = {"moves": list(reversed(moves)) if reverse_order else moves}

    execute_event(state, 32)

    assert count_pieces_by_state(state, rc.SEQUANI, rc.ARVERNI,
                                 rc.WARBAND, rc.HIDDEN) == 2
    assert count_pieces_by_state(state, rc.AEDUI_REGION, rc.ARVERNI,
                                 rc.WARBAND, rc.REVEALED) == 3
    assert count_pieces_by_state(state, rc.AEDUI_REGION, rc.ARVERNI,
                                 rc.WARBAND, rc.HIDDEN) == 0
    assert count_pieces_by_state(state, rc.AEDUI_REGION, rc.ARVERNI,
                                 rc.WARBAND, rc.SCOUTED) == 0
    _assert_sound(state)


